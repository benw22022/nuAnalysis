struct FaserNuBox {
    /*Dimensions of the Faser NuBox*/
    static constexpr float x_min = -115;
    static constexpr float x_max = 135;
  
    static constexpr float y_min = -171;
    static constexpr float y_max = 129;
  
    static constexpr float z_min = -3000;
    static constexpr float z_max = -1950;
    
    static bool isInside(float x, float y, float z) {
        return (x > x_min && x < x_max) &&
               (y > y_min && y < y_max) &&
               (z > z_min && z < z_max);
    }
};

struct LeadBlock {
    /*Dimensions of the Lead Block*/
    static constexpr float x_min = -300;
    static constexpr float x_max = 300;
    static constexpr float y_min = -300;
    static constexpr float y_max = 300;
    static constexpr float z_min = -1769.65;
    static constexpr float z_max = -1619.65;

    static bool isInside(float x, float y, float z) {
        return (x > x_min && x < x_max) &&
               (y > y_min && y < y_max) &&
               (z > z_min && z < z_max);
    }
};

struct CaloNuPMT{
  static constexpr float z_min = -2928.0;
  static constexpr float z_max = -2812.0;

  static bool isInside(float z) {
    return (z >= z_min && z <= z_max);
  }
};


