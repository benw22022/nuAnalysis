template<typename T>
RVec<T> inFaserNuBox(RVec<T> x, RVec<T> y, RVec<T> z) {
  RVec<bool> res(x.size(), false);
  for (int i(0); i < x.size(); i++) {
    if (FaserNuBox::isInside(x[i], y[i], z[i])) {
      res[i] = true;
    }
  }

  return res;
}

template<typename T>
bool inFaserNuBox(T x, T y, T z) {
  return FaserNuBox::isInside(x, y, z);
}

